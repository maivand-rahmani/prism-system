#!/usr/bin/env node
/**
 * Deterministic token artifact generation.
 *
 * A design system owns its visual language in `tokens.source.json`. From that
 * single source this module renders three shipped artifacts:
 *
 *   src/tokens/index.ts      the public TypeScript token export (refs resolved)
 *   src/styles/tokens.css    system-prefixed CSS custom properties (light/dark)
 *   src/styles/tailwind.css  a standalone Tailwind v4 `@theme` bridge
 *
 * `scripts/design-system-manifest.mjs` is the only validation authority: it runs
 * `parseTokenSource` (type-compatible, missing-target, and cycle checking) and
 * resolves every `$ref` to its ultimate literal before calling the pure
 * renderers here. This module never imports `tokens.source.json` itself and
 * never imports Tailwind or `@prism-system/ui-core`; it only formats strings.
 *
 * Rendering is a pure function of the resolved token tree plus `uiClass` and
 * `tokensExport`, so generation is stable and `--write`/check mode compare
 * byte-for-byte.
 */

import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

/** Package-relative path of the generated TypeScript token module. */
export const TOKENS_TYPESCRIPT_RELATIVE_PATH = "src/tokens/index.ts";
/** Package-relative path of the generated CSS custom-property file. */
export const TOKENS_CSS_RELATIVE_PATH = "src/styles/tokens.css";
/** Package-relative path of the generated Tailwind v4 bridge. */
export const TOKENS_TAILWIND_RELATIVE_PATH = "src/styles/tailwind.css";

/** The three token artifacts, in stable order. */
export const TOKEN_ARTIFACT_PATHS = Object.freeze([
  Object.freeze({ key: "typescript", relativePath: TOKENS_TYPESCRIPT_RELATIVE_PATH }),
  Object.freeze({ key: "css", relativePath: TOKENS_CSS_RELATIVE_PATH }),
  Object.freeze({ key: "tailwind", relativePath: TOKENS_TAILWIND_RELATIVE_PATH }),
]);

/**
 * The canonical Tailwind utility namespace every Tailwind v4 bridge aliases under.
 *
 * Rendered theme keys are `--color-<prefix>-…`, `--spacing-<prefix>-…`, and so
 * on, which produce the `bg-<prefix>-…` / `p-<prefix>-…` utility families. The
 * generated manifest publishes this exact value as `tokens.names
 * .tailwindUtilityPrefix`, so both the bridge and the manifest read the same
 * constant instead of duplicating the literal.
 */
export const TAILWIND_UTILITY_PREFIX = "prism";

/**
 * The exact `tokens.names` fields a manifest declares, in canonical order.
 * Both are required; an unknown or missing field fails closed.
 */
export const TOKEN_NAME_FIELDS = Object.freeze(["cssVariablePrefix", "tailwindUtilityPrefix"]);

/**
 * A safe lower-kebab namespace: starts with a lowercase letter, then
 * hyphen-separated lowercase alphanumeric words. Rejects empty strings, leading
 * digits, uppercase, dots, underscores, and whitespace.
 */
export const TOKEN_NAMESPACE_PATTERN = /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/;

const TOKENS_SOURCE_FILENAME = "tokens.source.json";

const GENERATED_TS_HEADER =
  "// Generated by prism-system from tokens.source.json. Do not edit by hand.";
const GENERATED_CSS_HEADER =
  "/* Generated by prism-system from tokens.source.json. Do not edit by hand. */";
const REGENERATE_HINT = "Regenerate with: pnpm ds:manifest <id> --write";

function isPlainObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function requireNonEmptyString(value, label) {
  if (typeof value !== "string" || value.trim().length === 0) {
    throw new Error(`Expected a non-empty string for "${label}".`);
  }
  return value.trim();
}

/**
 * The CSS variable prefix: `prismSystem.uiClass` minus a trailing `-ui`.
 * `maivand-a-ui` -> `maivand-a`. A value without the suffix is used verbatim.
 */
export function tokenVariablePrefix(uiClass) {
  const value = requireNonEmptyString(uiClass, "prismSystem.uiClass");
  return value.endsWith("-ui") ? value.slice(0, -3) : value;
}

/**
 * The canonical token naming contract for a system. `cssVariablePrefix` is the
 * same value {@link renderTokensCss} prefixes every custom property with, and
 * `tailwindUtilityPrefix` is the same namespace {@link renderTailwindCss}
 * aliases every `@theme` key under. Deriving both here keeps the generated
 * manifest and the generated artifacts from ever drifting.
 */
export function tokenNaming(uiClass) {
  return {
    cssVariablePrefix: tokenVariablePrefix(uiClass),
    tailwindUtilityPrefix: TAILWIND_UTILITY_PREFIX,
  };
}

/** `primaryHover` -> `primary-hover`, `2xl` -> `2xl`, `lineHeight` -> `line-height`. */
function toKebab(segment) {
  return segment.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
}

function kebabPath(path) {
  return path.map(toKebab).join("-");
}

/** Flatten a resolved token subtree into `{ path, value }` leaves in source order. */
function flattenLeaves(value, prefix = []) {
  if (isPlainObject(value)) {
    const leaves = [];
    for (const key of Object.keys(value)) {
      leaves.push(...flattenLeaves(value[key], [...prefix, key]));
    }
    return leaves;
  }
  return [{ path: prefix, value }];
}

function formatCssValue(value) {
  return typeof value === "string" ? value : String(value);
}

function toTypeName(tokensExport) {
  return `${tokensExport.charAt(0).toUpperCase()}${tokensExport.slice(1)}`;
}

/**
 * Render `src/tokens/index.ts`: the resolved token tree as a `const` export
 * plus a `typeof` type export. Pure and stable for a given input.
 */
export function renderTokensTypeScript({ tokensExport, resolvedTokens }) {
  const name = requireNonEmptyString(tokensExport, "prismSystem.tokensExport");
  const typeName = toTypeName(name);
  const body = JSON.stringify(resolvedTokens, null, 2);
  return [
    GENERATED_TS_HEADER,
    `// ${REGENERATE_HINT}`,
    "",
    `export const ${name} = ${body} as const;`,
    "",
    `export type ${typeName} = typeof ${name};`,
    "",
  ].join("\n");
}

/**
 * Render `src/styles/tokens.css`.
 *
 * Theme colors use one variable name for both themes (the `themes.light` /
 * `themes.dark` segments are omitted), so `themes.light.color.text.primary` and
 * its dark override share `--<prefix>-color-text-primary`. Light values are
 * declared under `:root`; dark values override under
 * `:root[data-prism-theme="dark"]`. Every other group maps its full dot path to
 * a kebab-case variable, e.g. `typography.family.sans` ->
 * `--<prefix>-typography-family-sans`.
 */
export function renderTokensCss({ uiClass, resolvedTokens }) {
  const prefix = tokenVariablePrefix(uiClass);
  const root = [];
  const dark = [];

  for (const leaf of flattenLeaves(resolvedTokens)) {
    const [group, theme] = leaf.path;
    if (group === "themes") {
      const declaration = `  --${prefix}-${kebabPath(leaf.path.slice(2))}: ${formatCssValue(
        leaf.value,
      )};`;
      if (theme === "dark") dark.push(declaration);
      else root.push(declaration);
      continue;
    }
    root.push(`  --${prefix}-${kebabPath(leaf.path)}: ${formatCssValue(leaf.value)};`);
  }

  const lines = [GENERATED_CSS_HEADER, `/* ${REGENERATE_HINT} */`, "", ":root {", ...root, "}"];
  if (dark.length > 0) {
    lines.push("", ':root[data-prism-theme="dark"] {', ...dark, "}");
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Render `src/styles/tailwind.css`: a standalone Tailwind v4 bridge that
 * aliases Tailwind semantic theme keys to this package's CSS variables. It
 * does not import Tailwind and it does not import the package stylesheet.
 *
 * Static breakpoints are emitted as literals under `@theme` (never `var()`),
 * because media-query breakpoints must resolve at build time. Motion durations
 * and z-layers intentionally get no named namespace: their package variables
 * remain usable through Tailwind custom-property utilities
 * (`duration-(--...)`, `z-(--...)`).
 */
export function renderTailwindCss({ uiClass, resolvedTokens }) {
  const prefix = tokenVariablePrefix(uiClass);
  const utility = TAILWIND_UTILITY_PREFIX;
  const ref = (varPath) => `var(--${prefix}-${kebabPath(varPath)})`;
  const aliases = [];
  const push = (name, varPath) => aliases.push(`  ${name}: ${ref(varPath)};`);

  // Colors: the light tree defines the names; dark overrides the same package
  // variables, so a single alias set serves both themes.
  for (const leaf of flattenLeaves(resolvedTokens.themes.light.color)) {
    push(`--color-${utility}-${kebabPath(leaf.path)}`, ["color", ...leaf.path]);
  }

  const { typography, spacing, containers, radius, shadow, motion } = resolvedTokens;
  for (const key of Object.keys(typography.family)) {
    push(`--font-${utility}-${toKebab(key)}`, ["typography", "family", key]);
  }
  for (const key of Object.keys(typography.size)) {
    push(`--text-${utility}-${toKebab(key)}`, ["typography", "size", key]);
  }
  for (const key of Object.keys(typography.weight)) {
    push(`--font-weight-${utility}-${toKebab(key)}`, ["typography", "weight", key]);
  }
  for (const key of Object.keys(typography.lineHeight)) {
    push(`--leading-${utility}-${toKebab(key)}`, ["typography", "lineHeight", key]);
  }
  for (const key of Object.keys(typography.letterSpacing)) {
    push(`--tracking-${utility}-${toKebab(key)}`, ["typography", "letterSpacing", key]);
  }
  // Spacing drops the structural `scale`/`semantic` subgroup so the utility
  // reads as `p-<utility>-4` / `p-<utility>-inline`.
  for (const leaf of flattenLeaves(spacing)) {
    push(`--spacing-${utility}-${toKebab(leaf.path[1])}`, ["spacing", ...leaf.path]);
  }
  for (const leaf of flattenLeaves(containers)) {
    push(`--container-${utility}-${kebabPath(leaf.path)}`, ["containers", ...leaf.path]);
  }
  for (const leaf of flattenLeaves(radius)) {
    push(`--radius-${utility}-${kebabPath(leaf.path)}`, ["radius", ...leaf.path]);
  }
  for (const leaf of flattenLeaves(shadow)) {
    push(`--shadow-${utility}-${kebabPath(leaf.path)}`, ["shadow", ...leaf.path]);
  }
  for (const leaf of flattenLeaves(motion.easing)) {
    push(`--ease-${utility}-${kebabPath(leaf.path)}`, ["motion", "easing", ...leaf.path]);
  }

  const breakpoints = [];
  for (const leaf of flattenLeaves(resolvedTokens.breakpoints)) {
    breakpoints.push(
      `  --breakpoint-${utility}-${kebabPath(leaf.path)}: ${formatCssValue(leaf.value)};`,
    );
  }

  return [
    GENERATED_CSS_HEADER,
    `/* ${REGENERATE_HINT} */`,
    '/* Standalone Tailwind v4 bridge: import after "tailwindcss". It does not import Tailwind. */',
    "",
    "@theme inline {",
    ...aliases,
    "}",
    "",
    "@theme {",
    ...breakpoints,
    "}",
    "",
  ].join("\n");
}

/**
 * Build the three artifact descriptors (`{ key, relativePath, content }`) from
 * an already-validated and fully resolved token tree. Pure and synchronous.
 */
export function buildTokenArtifactFiles({ tokensExport, uiClass, resolvedTokens }) {
  const contentByKey = {
    typescript: renderTokensTypeScript({ tokensExport, resolvedTokens }),
    css: renderTokensCss({ uiClass, resolvedTokens }),
    tailwind: renderTailwindCss({ uiClass, resolvedTokens }),
  };
  return TOKEN_ARTIFACT_PATHS.map((artifact) => ({
    ...artifact,
    content: contentByKey[artifact.key],
  }));
}

/**
 * Compare freshly rendered artifact descriptors against the on-disk files.
 * Reports a missing or drifted artifact for each mismatch.
 *
 * @returns {{ ok: boolean, failures: string[], artifacts: Record<string, { relativePath: string, ok: boolean, actual: string | null }> }}
 */
export function checkTokenArtifactFiles({ id, packageDir, files }) {
  const failures = [];
  const artifacts = {};
  for (const file of files) {
    const absolutePath = join(packageDir, file.relativePath);
    if (!existsSync(absolutePath)) {
      failures.push(
        `Missing generated token artifact ${file.relativePath}; regenerate it with ` +
          `"pnpm ds:manifest ${id} --write".`,
      );
      artifacts[file.key] = { relativePath: file.relativePath, ok: false, actual: null };
      continue;
    }
    const actual = readFileSync(absolutePath, "utf8");
    if (actual !== file.content) {
      failures.push(
        `Generated token artifact ${file.relativePath} is out of date with ` +
          `${TOKENS_SOURCE_FILENAME}; regenerate it with "pnpm ds:manifest ${id} --write".`,
      );
      artifacts[file.key] = { relativePath: file.relativePath, ok: false, actual };
      continue;
    }
    artifacts[file.key] = { relativePath: file.relativePath, ok: true, actual };
  }
  return { ok: failures.length === 0, failures, artifacts };
}
